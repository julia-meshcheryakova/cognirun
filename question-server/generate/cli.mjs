#!/usr/bin/env node
/**
 * Builds the committed question bank.
 *
 *   npm --prefix question-server run generate             write bank/library.generated.js
 *   npm --prefix question-server run generate -- --check  fail if the committed file is stale
 *   npm --prefix question-server run generate -- --groq-draft 10 [--category trivia]
 *       optional: ask Groq (GROQ_API_KEY from env) for draft questions, written to
 *       bank/review/ for a human to vet; never touches the bank itself.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { BANK_REQUIREMENTS, buildBank } from './build.js';
import { bankStats, validateBank } from './validate.js';

export const BANK_FILE = fileURLToPath(new URL('../bank/library.generated.js', import.meta.url));

/** The generated module: one question per line keeps diffs reviewable. */
export function renderBankModule(questions) {
  const lines = questions.map((q) => `  ${JSON.stringify(q)},`);
  return [
    '// GENERATED by `npm --prefix question-server run generate`. Do not edit by hand:',
    '// change bank/core.js, bank/trivia.js or generate/*.js and regenerate.',
    'export const BANK_QUESTIONS = [',
    ...lines,
    '];',
    '',
  ].join('\n');
}

function argValue(args, name) {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
}

async function main(args) {
  if (args.includes('--groq-draft')) {
    const { draftWithGroq } = await import('./groqDraft.mjs');
    const file = await draftWithGroq({
      count: Number(argValue(args, '--groq-draft')) || 10,
      category: argValue(args, '--category') ?? 'trivia',
    });
    console.log(`Drafts written to ${file}. Review them, then copy approved ones into bank/.`);
    return;
  }

  const questions = buildBank();
  const errors = validateBank(questions, BANK_REQUIREMENTS);
  if (errors.length) {
    console.error(`Invalid bank:\n  ${errors.join('\n  ')}`);
    process.exit(1);
  }
  const rendered = renderBankModule(questions);
  if (args.includes('--check')) {
    const current = readFileSync(BANK_FILE, 'utf8').replace(/\r\n/g, '\n');
    if (current !== rendered) {
      console.error('bank/library.generated.js is stale: run `npm --prefix question-server run generate`.');
      process.exit(1);
    }
    console.log('Bank is up to date.');
  } else {
    writeFileSync(BANK_FILE, rendered);
    console.log(`Wrote ${questions.length} questions to ${BANK_FILE}`);
  }
  console.table(bankStats(questions));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  await main(process.argv.slice(2));
}
